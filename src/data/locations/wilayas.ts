export const getWilayaName = (wilaya: Wilaya | undefined, lang: string = 'ar'): string => {
  if (!wilaya) return '';
  if (lang === 'fr') return wilaya.name_fr;
  if (lang === 'en') return wilaya.name_en;
  return wilaya.name_ar;
};
